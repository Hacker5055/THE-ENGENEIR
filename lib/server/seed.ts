function person(seedIndex: number) {
  const female = seedIndex % 3 === 0;
  const first = female ? FEMALE_FIRST[seedIndex % FEMALE_FIRST.length] : MALE_FIRST[seedIndex % MALE_FIRST.length];
  const family = FAMILY[(seedIndex * 7 + 3) % FAMILY.length];
  const nameAr = `${first} ${family}`;
  const nameEn = transliterate(nameAr);
  return { nameAr, nameEn, female, hue: (seedIndex * 47) % 360 };
}

